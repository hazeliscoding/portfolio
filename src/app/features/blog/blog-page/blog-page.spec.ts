import { ComponentFixture, TestBed } from '@angular/core/testing';
import { ActivatedRoute, provideRouter } from '@angular/router';
import { Meta, Title } from '@angular/platform-browser';
import { of } from 'rxjs';
import { BlogPage } from './blog-page';
import { blogPosts } from '../../../data/blog-posts.generated';

describe('BlogPage', () => {
  let fixture: ComponentFixture<BlogPage>;
  let el: HTMLElement;

  beforeEach(async () => {
    await TestBed.configureTestingModule({
      imports: [BlogPage],
      providers: [provideRouter([])],
    }).compileComponents();
    fixture = TestBed.createComponent(BlogPage);
    fixture.detectChanges();
    el = fixture.nativeElement as HTMLElement;
  });

  const rows = () => Array.from(el.querySelectorAll('.log__row'));

  it('should create', () => {
    expect(fixture.componentInstance).toBeTruthy();
  });

  it('renders the LOG_04 chapter header', () => {
    expect(el.querySelector('.chapter__code')?.textContent?.trim()).toBe('LOG');
    expect(el.querySelector('.chapter__index')?.textContent?.trim()).toBe('_04');
  });

  // Literal, because a test that recomputes the string from `count()` would
  // pass whatever the page printed. Update it when an entry lands.
  it('reports the entry count and the feed in the chapter meta', () => {
    expect(el.querySelector('.chapter__meta')?.textContent?.trim()).toBe('3 ENTRIES · RSS');
  });

  it('links the RSS feed generated by scripts/generate-blog.mjs', () => {
    const feed = el.querySelector('.chapter__meta a');
    expect(feed?.getAttribute('href')).toBe('/feed.xml');
    expect(feed?.getAttribute('type')).toBe('application/rss+xml');
  });

  it('offers every tag in use as a filter, with ALL marked current', () => {
    const links = Array.from(el.querySelectorAll('.log__filter-link'));
    const tags = new Set(blogPosts.flatMap((post) => post.tags));
    expect(links.length).toBe(tags.size + 1);
    expect(links[0].getAttribute('aria-current')).toBe('page');
    expect(links[1].getAttribute('href')).toMatch(/^\/blog\/tags\/[a-z0-9-]+$/);
  });

  it('sets the document title', () => {
    expect(TestBed.inject(Title).getTitle()).toContain('Blog');
  });

  it('introduces the log', () => {
    expect(el.querySelector('.log__intro')?.textContent?.trim()).toBe(
      'Short notes about building, learning, and shipping software.',
    );
  });

  it('renders the entries as one active, unpadded dialogue panel', () => {
    const win = el.querySelector('.window') as HTMLElement;
    expect(win.getAttribute('data-variant')).toBe('dialogue');
    expect(win.getAttribute('data-active')).toBe('true');
    expect(win.style.animationDelay).toBe('60ms');
    expect(
      el.querySelector('.window__body')?.classList.contains('window__body--padded'),
    ).toBe(false);
    expect(el.querySelector('.window__foot')?.textContent).toContain('OPEN ENTRY');
  });

  it('renders one row per post', () => {
    expect(rows().length).toBe(blogPosts.length);
  });

  it('links the whole row to its entry', () => {
    expect(rows()[0].getAttribute('href')).toBe(`/blog/${blogPosts[0].slug}`);
  });

  it('stamps each row with its date and four-digit entry number', () => {
    const stamp = rows()[0].querySelector('.log__stamp')?.textContent ?? '';
    expect(stamp).toContain(blogPosts[0].date);
    // Entries are numbered oldest-first, so the last row is always 0001.
    const all = rows();
    const last = all[all.length - 1].querySelector('.log__stamp')?.textContent ?? '';
    expect(last).toContain('0001');
  });

  it('renders the title and description of each entry', () => {
    expect(rows()[0].querySelector('.log__title')?.textContent?.trim()).toBe(
      blogPosts[0].title,
    );
    expect(rows()[0].querySelector('.log__desc')?.textContent?.trim()).toBe(
      blogPosts[0].description,
    );
  });

  it('renders every tag as an info badge', () => {
    const badges = Array.from(rows()[0].querySelectorAll('.log__tags .badge'));
    expect(badges.length).toBe(blogPosts[0].tags.length);
    expect(badges[0].getAttribute('data-tone')).toBe('info');
    expect(badges.map((b) => b.textContent?.trim())).toEqual(blogPosts[0].tags);
  });

  it('contains no emoji', () => {
    const text = el.textContent ?? '';
    expect(/\p{Extended_Pictographic}/u.test(text)).toBe(false);
  });
});

describe('BlogPage on /blog/tags/:tag', () => {
  const setup = async (tag: string) => {
    await TestBed.configureTestingModule({
      imports: [BlogPage],
      providers: [
        provideRouter([]),
        { provide: ActivatedRoute, useValue: { paramMap: of(new Map([['tag', tag]])) } },
      ],
    }).compileComponents();
    const fixture = TestBed.createComponent(BlogPage);
    fixture.detectChanges();
    return fixture.nativeElement as HTMLElement;
  };

  it('lists only the entries carrying the tag, keeping their entry numbers', async () => {
    const el = await setup('claude-code');
    const tagged = blogPosts.filter((post) => post.tags.includes('claude-code'));
    const rows = Array.from(el.querySelectorAll('.log__row'));
    expect(rows.length).toBe(tagged.length);
    expect(rows.map((r) => r.getAttribute('href'))).toEqual(
      tagged.map((post) => `/blog/${post.slug}`),
    );
    expect(el.querySelector('.log__intro')?.textContent?.trim()).toBe('Entries tagged claude-code.');
  });

  it('marks the tag current in the filter', async () => {
    const el = await setup('claude-code');
    const current = el.querySelector('.log__filter-link[aria-current="page"]');
    expect(current?.getAttribute('href')).toBe('/blog/tags/claude-code');
  });

  // Two entries is below the indexing threshold: a reader can follow the tag,
  // search engines are asked to skip it, and the sitemap leaves it out.
  it('keeps a thin tag listing out of search', async () => {
    await setup('claude-code');
    expect(TestBed.inject(Meta).getTag("name='robots'")?.content).toBe('noindex');
    expect(TestBed.inject(Title).getTitle()).toBe('Entries tagged claude-code - Hazel Granados');
  });

  it('says so when no entry carries the tag', async () => {
    const el = await setup('no-such-tag');
    expect(el.querySelectorAll('.log__row').length).toBe(0);
    expect(el.querySelector('.log__empty')?.textContent).toContain('NO ENTRIES CARRY THIS TAG');
  });
});
