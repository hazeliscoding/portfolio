import { ComponentFixture, TestBed } from '@angular/core/testing';
import { ActivatedRoute, provideRouter } from '@angular/router';
import { Meta, Title } from '@angular/platform-browser';
import { of } from 'rxjs';
import { BlogPage } from './blog-page';
import { blogPosts } from '../../../data/blog-posts.generated';

describe('BlogPage', () => {
  let fixture: ComponentFixture<BlogPage>;
  let el: HTMLElement;

  beforeEach(async () => {
    await TestBed.configureTestingModule({
      imports: [BlogPage],
      providers: [provideRouter([])],
    }).compileComponents();
    fixture = TestBed.createComponent(BlogPage);
    fixture.detectChanges();
    el = fixture.nativeElement as HTMLElement;
  });

  const cards = () => Array.from(el.querySelectorAll('.entry'));
  const link = (card: Element) => card.querySelector('.entry__link');

  it('should create', () => {
    expect(fixture.componentInstance).toBeTruthy();
  });

  it('opens with the page heading', () => {
    const headings = Array.from(el.querySelectorAll('h1'));
    expect(headings.length).toBe(1);
    expect(headings[0].textContent?.trim()).toBe('Writing.');
  });

  // Literal, because a test that recomputes the string from `count()` would
  // pass whatever the page printed. Update it when a post lands.
  it('reports the post count beside the feed', () => {
    expect(el.querySelector('.blog__meta')?.textContent?.trim()).toBe('5 posts · RSS feed');
  });

  it('links the RSS feed generated by scripts/generate-blog.mjs', () => {
    const feed = el.querySelector('.blog__feed');
    expect(feed?.getAttribute('href')).toBe('/feed.xml');
    expect(feed?.getAttribute('type')).toBe('application/rss+xml');
  });

  it('offers every tag in use as a filter, with All marked current', () => {
    const links = Array.from(el.querySelectorAll('.blog__filter-link'));
    const tags = new Set(blogPosts.flatMap((post) => post.tags));
    expect(links.length).toBe(tags.size + 1);
    expect(links[0].textContent?.trim()).toBe('All');
    expect(links[0].getAttribute('aria-current')).toBe('page');
    expect(links[1].getAttribute('href')).toMatch(/^\/blog\/tags\/[a-z0-9-]+$/);
  });

  it('sets the document title', () => {
    expect(TestBed.inject(Title).getTitle()).toContain('Blog');
  });

  it('introduces the blog', () => {
    expect(el.querySelector('.blog__intro')?.textContent?.trim()).toContain(
      'Write-ups of what I build and how I prove it works',
    );
  });

  it('renders one card per post, newest first', () => {
    expect(cards().length).toBe(blogPosts.length);
    expect(link(cards()[0])?.getAttribute('href')).toBe(`/blog/${blogPosts[0].slug}`);
  });

  it('leads with the newest post, and only on the full blog', () => {
    expect(cards()[0].classList.contains('entry--lead')).toBe(true);
    expect(el.querySelectorAll('.entry--lead').length).toBe(1);
  });

  it('dates each card', () => {
    const date = cards()[0].querySelector('.entry__date');
    expect(date?.textContent?.trim()).toBe(blogPosts[0].date);
    expect(date?.getAttribute('datetime')).toBe(blogPosts[0].date);
  });

  it('renders the title and description of each post', () => {
    expect(link(cards()[0])?.textContent?.trim()).toBe(blogPosts[0].title);
    expect(cards()[0].querySelector('.entry__desc')?.textContent?.trim()).toBe(
      blogPosts[0].description,
    );
  });

  it('links every tag on a card to its listing', () => {
    const tags = Array.from(cards()[0].querySelectorAll('.entry__tag'));
    expect(tags.map((t) => t.textContent?.trim())).toEqual(blogPosts[0].tags);
    expect(tags[0].getAttribute('href')).toBe(`/blog/tags/${blogPosts[0].tags[0]}`);
  });

  it('labels each part of a series with its name and number, oldest part first', () => {
    const parts = blogPosts.filter((post) => post.series === 'Puzzle Boy');
    const label = (slug: string) =>
      cards()
        .find((card) => link(card)?.getAttribute('href') === `/blog/${slug}`)
        ?.querySelector('.entry__series')
        ?.textContent?.trim();
    expect(label(parts[parts.length - 1].slug)).toBe('Puzzle Boy · Part 1');
    expect(label(parts[0].slug)).toBe(`Puzzle Boy · Part ${parts.length}`);
    expect(label('hello-world')).toBeUndefined();
  });

  it('contains no emoji', () => {
    const text = el.textContent ?? '';
    expect(/\p{Extended_Pictographic}/u.test(text)).toBe(false);
  });
});

describe('BlogPage on /blog/tags/:tag', () => {
  const setup = async (tag: string) => {
    await TestBed.configureTestingModule({
      imports: [BlogPage],
      providers: [
        provideRouter([]),
        { provide: ActivatedRoute, useValue: { paramMap: of(new Map([['tag', tag]])) } },
      ],
    }).compileComponents();
    const fixture = TestBed.createComponent(BlogPage);
    fixture.detectChanges();
    return fixture.nativeElement as HTMLElement;
  };

  it('lists only the posts carrying the tag, with no lead card', async () => {
    const el = await setup('claude-code');
    const tagged = blogPosts.filter((post) => post.tags.includes('claude-code'));
    const links = Array.from(el.querySelectorAll('.entry__link'));
    expect(links.map((a) => a.getAttribute('href'))).toEqual(
      tagged.map((post) => `/blog/${post.slug}`),
    );
    expect(el.querySelector('.entry--lead')).toBeNull();
    expect(el.querySelector('h1')?.textContent?.trim()).toBe('claude-code');
    expect(el.querySelector('.blog__intro')?.textContent?.trim()).toBe('Posts tagged claude-code.');
  });

  it('marks the tag current in the filter', async () => {
    const el = await setup('claude-code');
    const current = el.querySelector('.blog__filter-link[aria-current="page"]');
    expect(current?.getAttribute('href')).toBe('/blog/tags/claude-code');
  });

  // One post is below the indexing threshold: a reader can follow the tag,
  // search engines are asked to skip it, and the sitemap leaves it out.
  it('keeps a thin tag listing out of search', async () => {
    await setup('ghidra');
    expect(TestBed.inject(Meta).getTag("name='robots'")?.content).toBe('noindex');
    expect(TestBed.inject(Title).getTitle()).toBe('Entries tagged ghidra - Hazel Granados');
  });

  it('says so when no post carries the tag', async () => {
    const el = await setup('no-such-tag');
    expect(el.querySelectorAll('.entry').length).toBe(0);
    expect(el.querySelector('.blog__empty')?.textContent).toContain('No posts carry this tag yet.');
  });
});
