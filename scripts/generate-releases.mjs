import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';

// Generates src/app/data/releases.generated.ts from the public GitHub API.
//
//   node scripts/generate-releases.mjs
//
// Also runs weekly from .github/workflows/releases.yml, which commits the
// result only when a release actually changed.
//
// The repos come from projects.data.ts itself — every github.com/<USER>/<repo>
// link in it — so adding a project there is all it takes to track its
// releases. A second hand-kept list would drift the same way Prompuff's
// platforms did when they lived in prose.

const USER = 'hazeliscoding';

const dataDir = path.join(process.cwd(), 'src', 'app', 'data');
const projectsFile = path.join(dataDir, 'projects.data.ts');
const outputFile = path.join(dataDir, 'releases.generated.ts');

const token = process.env.GITHUB_TOKEN || process.env.GH_TOKEN || '';

/** The JSON body, or null for a 404: a repo with no release yet is not an error. */
async function gh(url) {
  const res = await fetch(url, {
    headers: {
      Accept: 'application/vnd.github+json',
      ...(token ? { Authorization: `Bearer ${token}` } : {}),
    },
  });
  if (res.status === 404) return null;
  if (!res.ok) {
    const remaining = res.headers.get('x-ratelimit-remaining');
    const hint =
      res.status === 403 && remaining === '0'
        ? ' — rate limit exhausted; set GITHUB_TOKEN or retry later'
        : '';
    throw new Error(`GitHub API ${res.status} for ${url}${hint}`);
  }
  return res.json();
}

// Only files someone downloads to run count; update manifests (latest.yml,
// releases.win.json), delta packages (.nupkg), blockmaps and checksums would
// otherwise claim platforms on their own — `latest-linux.yml` names Linux.
const INSTALLABLE = /\.(exe|msi|zip|tar\.gz|appimage|pkg|dmg|deb|rpm)$/i;

// `win` must not be preceded by a letter, or "darwin" reads as Windows.
const PLATFORMS = [
  ['Windows', /(^|[^a-z])win|\.(exe|msi)$/i],
  ['macOS', /(^|[^a-z])(mac|osx|darwin)|\.(pkg|dmg)$/i],
  ['Linux', /linux|\.(appimage|deb|rpm)$/i],
];

function platformsOf(assetNames) {
  const files = assetNames.filter((name) => INSTALLABLE.test(name));
  return PLATFORMS.filter(([, pattern]) => files.some((name) => pattern.test(name))).map(
    ([platform]) => platform,
  );
}

// Self-check on real asset lists, before any request: a pattern that drifts
// would otherwise only show up as a wrong platform line on the live site.
assert.deepEqual(
  platformsOf(['latest-linux.yml', 'latest.yml', 'pr-sweep-0.13.0-setup.exe', 'pr-sweep-0.13.0.AppImage']),
  ['Windows', 'Linux'],
);
assert.deepEqual(
  platformsOf(['axm-0.5.0-linux-x64.tar.gz', 'axm-0.5.0-osx-arm64.tar.gz', 'axm-0.5.0-win-x64.zip', 'SHA256SUMS']),
  ['Windows', 'macOS', 'Linux'],
);
assert.deepEqual(platformsOf(['XivVault-1.0.0-full.nupkg', 'releases.win.json']), []);
assert.deepEqual(platformsOf(['tool-darwin-arm64.tar.gz']), ['macOS']);

async function readExisting() {
  const marker = 'export const releases: Record<string, Release> = ';
  try {
    const source = await fs.readFile(outputFile, 'utf8');
    const start = source.indexOf(marker);
    if (start === -1) return null;
    return JSON.parse(source.slice(start + marker.length).trim().replace(/;$/, ''));
  } catch {
    return null;
  }
}

const source = await fs.readFile(projectsFile, 'utf8');
const repos = [
  ...new Set(
    [...source.matchAll(new RegExp(`github\\.com/${USER}/([\\w.-]+)`, 'g'))].map((m) => m[1]),
  ),
].sort();

const releases = {};
for (const repo of repos) {
  const latest = await gh(`https://api.github.com/repos/${USER}/${repo}/releases/latest`);
  if (!latest) continue;
  releases[repo] = {
    tag: latest.tag_name,
    url: latest.html_url,
    platforms: platformsOf(latest.assets.map((a) => a.name)),
  };
}

// Same guard as the OSS stats: an API that answers but finds nothing is far
// likelier to be GitHub having a moment than every release vanishing, and
// unattended the site would quietly lose every version badge.
const previous = await readExisting();
const count = Object.keys(releases).length;
if (previous && Object.keys(previous).length > 0 && count === 0) {
  throw new Error(
    `Refusing to overwrite ${Object.keys(previous).length} releases with 0. ` +
      'The API answered but matched nothing; re-run before trusting this.',
  );
}

const ts = `/* eslint-disable */
// This file is auto-generated by scripts/generate-releases.mjs.
// Do not edit by hand.

export type Platform = 'Windows' | 'macOS' | 'Linux';

export type Release = {
  tag: string;
  /** The release page, which offers every platform's download. */
  url: string;
  /** Platforms the release ships an installable file for; empty for source-only releases. */
  platforms: Platform[];
};

/** Latest release per repo under github.com/${USER}, keyed by repo name. */
export const releases: Record<string, Release> = ${JSON.stringify(releases, null, 2)};
`;

await fs.writeFile(outputFile, ts, 'utf8');
console.log(`Wrote ${count} releases from ${repos.length} linked repos to ${outputFile}`);
